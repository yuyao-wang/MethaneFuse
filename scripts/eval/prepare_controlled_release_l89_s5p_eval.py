def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def event_key(value: object) -> str:
    text = str(value).strip()
    for prefix in ("cr_", "s5p_"):
        if text.startswith(prefix):
            return text[len(prefix) :]
    return text


def resolve_path(value: object) -> Path:
    path = Path(str(value).strip())
    return path if path.is_absolute() else REPO_ROOT / path


def inspect_tiffs(paths: list[Path]) -> dict:
    shapes: dict[str, int] = {}
    dtypes: dict[str, int] = {}
    nonfinite = 0
    missing = 0
    first7_min = np.inf
    first7_max = -np.inf
    first7_sum = 0.0
    first7_sq_sum = 0.0
    first7_count = 0
    for path in paths:
        if not path.is_file():
            missing += 1
            continue
        array = tifffile.imread(path)
        shapes[str(tuple(array.shape))] = shapes.get(str(tuple(array.shape)), 0) + 1
        dtypes[str(array.dtype)] = dtypes.get(str(array.dtype), 0) + 1
        nonfinite += int(array.size - np.isfinite(array).sum())
        values = np.asarray(array[:7], dtype=np.float64)
        finite = values[np.isfinite(values)]
        if finite.size:
            first7_min = min(first7_min, float(finite.min()))
            first7_max = max(first7_max, float(finite.max()))
            first7_sum += float(finite.sum())
            first7_sq_sum += float(np.square(finite).sum())
            first7_count += int(finite.size)
    mean = first7_sum / first7_count if first7_count else None
    variance = first7_sq_sum / first7_count - mean * mean if first7_count else None
    return {
        "count": len(paths),
        "missing": missing,
        "shapes": shapes,
        "dtypes": dtypes,
        "nonfinite_values": nonfinite,
        "first7_min": None if first7_count == 0 else first7_min,
        "first7_max": None if first7_count == 0 else first7_max,
        "first7_mean": mean,
        "first7_std": None if variance is None else float(np.sqrt(max(0.0, variance))),
    }


def training_reference_paths(manifest_path: Path, count: int) -> list[Path]:
    frame = pd.read_csv(manifest_path, usecols=list(L89_PATH_COLUMNS), low_memory=False)
    paths: list[Path] = []
    for column in L89_PATH_COLUMNS:
        values = frame[column].dropna().astype(str)
        paths.extend(Path(value) for value in values if value.strip())
    unique = sorted(set(paths))
    if len(unique) <= count:
        return unique
    rng = np.random.default_rng(360)
    indices = np.sort(rng.choice(len(unique), size=count, replace=False))
    return [unique[int(index)] for index in indices]


def training_s5p_reference_paths(manifest_path: Path, count: int) -> list[Path]:
    frame = pd.read_csv(manifest_path, usecols=["s5p_0_path"], low_memory=False)
    unique = sorted(
        {
            Path(value)
            for value in frame["s5p_0_path"].dropna().astype(str)
            if value.strip()
        }
    )
    if len(unique) <= count:
        return unique
    rng = np.random.default_rng(361)
    indices = np.sort(rng.choice(len(unique), size=count, replace=False))
    return [unique[int(index)] for index in indices]


def inspect_s5p_npz(paths: list[Path]) -> dict:
    shapes: dict[str, int] = {}
    dtypes: dict[str, int] = {}
    key_sets: dict[str, int] = {}
    missing = 0
    nonfinite = 0
    values_sum = 0.0
    values_sq_sum = 0.0
    values_count = 0
    values_min = np.inf
    values_max = -np.inf
    for path in paths:
        if not path.is_file():
            missing += 1
            continue
        with np.load(path, allow_pickle=False) as npz:
            keys = ",".join(sorted(npz.files))
            key_sets[keys] = key_sets.get(keys, 0) + 1
            array = np.asarray(npz["ch4"])
        shapes[str(tuple(array.shape))] = shapes.get(str(tuple(array.shape)), 0) + 1
        dtypes[str(array.dtype)] = dtypes.get(str(array.dtype), 0) + 1
        finite_mask = np.isfinite(array)
        nonfinite += int(array.size - finite_mask.sum())
        finite = np.asarray(array[finite_mask], dtype=np.float64)
        if finite.size:
            values_min = min(values_min, float(finite.min()))
            values_max = max(values_max, float(finite.max()))
            values_sum += float(finite.sum())
            values_sq_sum += float(np.square(finite).sum())
            values_count += int(finite.size)
    mean = values_sum / values_count if values_count else None
    variance = values_sq_sum / values_count - mean * mean if values_count else None
    return {
        "count": len(paths),
        "missing": missing,
        "shapes": shapes,
        "dtypes": dtypes,
        "key_sets": key_sets,
        "nonfinite_values": nonfinite,
        "finite_min": None if values_count == 0 else values_min,
        "finite_max": None if values_count == 0 else values_max,
        "finite_mean": mean,
        "finite_std": None if variance is None else float(np.sqrt(max(0.0, variance))),
    }


def l89_loader_contract_check(manifest_path: Path) -> dict:
    dataset = TriSensorTemporalCsvDataset(
        csv_path=str(manifest_path),
        pad_to_multiple=14,
    )
    sensor_samples, label = dataset[0]
    if len(sensor_samples) != 1 or sensor_samples[0][0] != "l89":
        raise RuntimeError(f"Expected one L89 sensor sample, got {sensor_samples}")
    frames = sensor_samples[0][1]
    source = tifffile.imread(resolve_path(dataset.df.iloc[0]["l89_0_path"]))
    mean = np.asarray(L89_PRECOMPUTED_STATS[0], dtype=np.float32)[:, None, None]
    std = np.asarray(L89_PRECOMPUTED_STATS[1], dtype=np.float32)[:, None, None]
    expected = np.clip((source[:7].astype(np.float32) - mean) / std, -50.0, 50.0)
    observed = frames[0]["imgs"].numpy()
    return {
        "label": int(label),
        "frames": len(frames),
        "frame_shapes": [list(frame["imgs"].shape) for frame in frames],
        "channel_id_shapes": [list(frame["chn_ids"].shape) for frame in frames],
        "all_finite": bool(all(np.isfinite(frame["imgs"].numpy()).all() for frame in frames)),
        "direct_normalization_max_abs_error": float(np.max(np.abs(observed - expected))),
    }


def s5p_loader_contract_check(manifest_path: Path) -> dict:
    dataset = TriSensorTemporalCsvDataset(
        csv_path=str(manifest_path),
        pad_to_multiple=14,
    )
    sensor_samples, label = dataset[0]
    if len(sensor_samples) != 1 or sensor_samples[0][0] != "s5p":
        raise RuntimeError(f"Expected one S5P sensor sample, got {sensor_samples}")
    frame = sensor_samples[0][1][0]
    source_path = resolve_path(dataset.df.iloc[0]["s5p_0_path"])
    with np.load(source_path, allow_pickle=False) as npz:
        source = np.asarray(npz["ch4"], dtype=np.float32)
    mean = np.asarray(S5P_PRECOMPUTED_STATS[0], dtype=np.float32)[:, None, None]
    std = np.asarray(S5P_PRECOMPUTED_STATS[1], dtype=np.float32)[:, None, None]
    expected = (np.nan_to_num(source, nan=0.0, posinf=0.0, neginf=0.0) - mean) / std
    observed = frame["imgs"].numpy()
    return {
        "label": int(label),
        "frame_shape": list(frame["imgs"].shape),
        "channel_id_shape": list(frame["chn_ids"].shape),
        "all_finite": bool(np.isfinite(observed).all()),
        "direct_normalization_max_abs_error": float(np.max(np.abs(observed - expected))),
    }


def write_manifest(frame: pd.DataFrame, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(path, index=False)


def main() -> None:
    args = parse_args()
    l89_manifest_path = args.l89_dir / "manifest.csv"
    l89_download_path = REPO_ROOT / "data/controlled_release_test/l89_gee_download.csv"
    s5p_manifest_path = args.s5p_dir / "s5p_model_manifest.csv"

    l89 = pd.read_csv(l89_manifest_path, low_memory=False)
    l89["event_key"] = l89["plume_id"].map(event_key)
    l89_download = pd.read_csv(l89_download_path, low_memory=False)
    l89_t0 = l89_download.loc[l89_download["timepoint"].eq("t0")].copy()
    l89_t0["event_key"] = l89_t0["plume_id"].map(event_key)
    event_to_datetime = dict(zip(l89_t0["event_key"], l89_t0["event_time"]))
    l89["datetime"] = l89["event_key"].map(event_to_datetime)

    s5p = pd.read_csv(s5p_manifest_path, low_memory=False)
    s5p["event_key"] = s5p["id"].map(event_key)
    s5p_path_by_key = dict(zip(s5p["event_key"], s5p["s5p_0_path"]))

    l89_all_path = args.l89_dir / "manifest_all_available.csv"
    l89_trusted_path = args.l89_dir / "manifest_trusted9_overlap.csv"
    s5p_all_path = args.s5p_dir / "s5p_model_manifest_all_available.csv"
    s5p_trusted_path = args.s5p_dir / "s5p_model_manifest_trusted9_overlap.csv"
    fusion_dir = REPO_ROOT / "data/controlled_release_test/l89_s5p_legacy360_positive"
    fusion_all_path = fusion_dir / "manifest_all_available_intersection.csv"
    fusion_trusted_path = fusion_dir / "manifest_trusted9_overlap.csv"

    output_columns = [column for column in l89.columns if column != "event_key"]
    write_manifest(l89[output_columns], l89_all_path)
    write_manifest(l89.loc[l89["event_key"].isin(TRUSTED_KEYS), output_columns], l89_trusted_path)
    write_manifest(s5p[[column for column in s5p.columns if column != "event_key"]], s5p_all_path)
    write_manifest(
        s5p.loc[s5p["event_key"].isin(TRUSTED_KEYS), [column for column in s5p.columns if column != "event_key"]],
        s5p_trusted_path,
    )

    fusion = l89.loc[l89["event_key"].isin(s5p_path_by_key)].copy()
    fusion["s5p_0_path"] = fusion["event_key"].map(s5p_path_by_key)
    fusion["anchor_sensor"] = "l89+s5p"
    write_manifest(fusion[output_columns], fusion_all_path)
    write_manifest(
        fusion.loc[fusion["event_key"].isin(TRUSTED_KEYS), output_columns],
        fusion_trusted_path,
    )

    candidate_paths = [
        resolve_path(value)
        for column in L89_PATH_COLUMNS
        for value in l89[column].dropna().astype(str)
        if value.strip()
    ]
    reference_paths = training_reference_paths(args.train_manifest, args.training_reference_count)
    s5p_candidate_paths = [resolve_path(value) for value in s5p["s5p_0_path"].astype(str)]
    s5p_reference_paths = training_s5p_reference_paths(
        args.train_manifest, args.training_reference_count
    )
    candidate_audit = inspect_tiffs(candidate_paths)
    reference_audit = inspect_tiffs(reference_paths)
    s5p_candidate_audit = inspect_s5p_npz(s5p_candidate_paths)
    s5p_reference_audit = inspect_s5p_npz(s5p_reference_paths)
    loader_audit = l89_loader_contract_check(l89_all_path)
    s5p_loader_audit = s5p_loader_contract_check(s5p_all_path)
    offsets_in_range = bool(
        l89["dx_anchor_px"].between(-3, 3).all() and l89["dy_anchor_px"].between(-3, 3).all()
    )
    audit_pass = bool(
        len(l89) == 64
        and candidate_audit["missing"] == 0
        and candidate_audit["shapes"] == {"(10, 224, 224)": len(candidate_paths)}
        and candidate_audit["dtypes"] == {"float32": len(candidate_paths)}
        and candidate_audit["nonfinite_values"] == 0
        and offsets_in_range
        and loader_audit["frame_shapes"] == [[7, 224, 224]] * 3
        and loader_audit["all_finite"]
        and loader_audit["direct_normalization_max_abs_error"] <= 1e-5
        and reference_audit["missing"] == 0
        and set(reference_audit["shapes"]) == {"(10, 224, 224)"}
        and set(reference_audit["dtypes"]) == {"float32"}
        and s5p_candidate_audit["missing"] == 0
        and s5p_candidate_audit["shapes"] == {"(3, 224, 224)": len(s5p_candidate_paths)}
        and s5p_candidate_audit["dtypes"] == {"float32": len(s5p_candidate_paths)}
        and s5p_reference_audit["missing"] == 0
        and set(s5p_reference_audit["shapes"]) == {"(3, 224, 224)"}
        and set(s5p_reference_audit["dtypes"]) == {"float32"}
        and s5p_loader_audit["frame_shape"] == [3, 224, 224]
        and s5p_loader_audit["all_finite"]
        and s5p_loader_audit["direct_normalization_max_abs_error"] <= 1e-5
    )
    audit = {
        "pass": audit_pass,
        "query_size_m": 360,
        "legacy_script": str(args.legacy_script),
        "legacy_script_sha256": sha256(args.legacy_script),
        "l89_manifest": str(l89_manifest_path),
        "l89_manifest_sha256": sha256(l89_manifest_path),
        "training_manifest": str(args.train_manifest),
        "training_reference_count": len(reference_paths),
        "s5p_training_reference_count": len(s5p_reference_paths),
        "candidate_rows": len(l89),
        "candidate_events": sorted(l89["event_key"].unique().tolist()),
        "candidate_tiffs": candidate_audit,
        "training_reference_tiffs": reference_audit,
        "offsets_within_legacy_positive_rule_minus3_to_plus3": offsets_in_range,
        "loader_contract": loader_audit,
        "s5p_candidate_npz": s5p_candidate_audit,
        "s5p_training_reference_npz": s5p_reference_audit,
        "s5p_loader_contract": s5p_loader_audit,
        "manifests": {
            "l89_all": {"path": str(l89_all_path), "rows": len(l89)},
            "l89_trusted9_overlap": {
                "path": str(l89_trusted_path),
                "rows": int(l89["event_key"].isin(TRUSTED_KEYS).sum()),
            },
            "s5p_all": {"path": str(s5p_all_path), "rows": len(s5p)},
            "s5p_trusted9_overlap": {
                "path": str(s5p_trusted_path),
                "rows": int(s5p["event_key"].isin(TRUSTED_KEYS).sum()),
            },
            "fusion_all_intersection": {"path": str(fusion_all_path), "rows": len(fusion)},
            "fusion_trusted9_overlap": {
                "path": str(fusion_trusted_path),
                "rows": int(fusion["event_key"].isin(TRUSTED_KEYS).sum()),
            },
        },
    }
    audit_path = args.l89_dir / "strict_input_audit.json"
    audit_path.write_text(json.dumps(audit, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps(audit, indent=2, sort_keys=True))
    if not audit_pass:
        raise SystemExit("Strict L89 input audit failed.")


if __name__ == "__main__":
    main()
