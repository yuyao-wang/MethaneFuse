#!/usr/bin/env python3
"""Leakage-safe past-to-current latent prediction and innovation probes for L89.

This runner consumes the frozen Panopticon CLS caches produced by
``l89_ragged_cls_experiment.py``.  It deliberately has two separate stages:

``pretrain``
    Fit a history-only predictor of the current (t0) CLS.  Training predictions
    are generated by deterministic canonical-event K-fold cross-fitting, so
    every downstream training residual is out-of-fold.  Validation predictions
    come from a final predictor fitted on all training events.

``downstream``
    Train parameter-identical lightweight classifiers on t0, predicted
    background, or innovation representations.  The sealed test set is never
    accepted or read.

The predictor API never receives a t0 tensor.  Cross-fitting and cache/event
alignment are validated fail-closed before any downstream optimization.
"""

