def validate_common_args(args: argparse.Namespace) -> None:
    for name in ("epochs", "batch_size", "eval_batch_size"):
        if int(getattr(args, name)) <= 0:
            raise ValueError(f"--{name.replace('_', '-')} must be positive.")
    if int(args.max_train_steps) < 0:
        raise ValueError("--max-train-steps cannot be negative.")
    if float(args.learning_rate) <= 0:
        raise ValueError("--learning-rate must be positive.")
    if float(args.weight_decay) < 0 or float(args.grad_clip) < 0:
        raise ValueError("weight decay and grad clip cannot be negative.")
    if int(args.model_dim) <= 0:
        raise ValueError("--model-dim must be positive.")
    if not 0 <= float(args.dropout) < 1:
        raise ValueError("--dropout must be in [0,1).")
    if args.command == "pretrain":
        if int(args.folds) < 2:
            raise ValueError("--folds must be at least 2.")
        if int(args.num_heads) <= 0 or int(args.model_dim) % int(args.num_heads):
            raise ValueError("--model-dim must be divisible by --num-heads.")
        if float(args.cosine_weight) < 0:
            raise ValueError("--cosine-weight cannot be negative.")


def main(argv: Optional[Sequence[str]] = None) -> None:
    parser = build_parser()
    args = parser.parse_args(argv)
    validate_common_args(args)
    args.func(args)


if __name__ == "__main__":
    main()
