def predictor_loss_terms(
    prediction: torch.Tensor,
    target: torch.Tensor,
    *,
    cosine_weight: float,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    if prediction.shape != target.shape or prediction.ndim != 2:
        raise ValueError("prediction and target must have equal shape (B,D).")
    mse = F.mse_loss(prediction, target)
    cosine_distance = (
        1.0 - F.cosine_similarity(prediction, target, dim=-1, eps=1e-8)
    ).mean()
    objective = mse + float(cosine_weight) * cosine_distance
    return objective, mse, cosine_distance


def reconstruction_metrics(
    prediction: torch.Tensor,
    target: torch.Tensor,
) -> dict[str, float | int]:
    if prediction.shape != target.shape or prediction.ndim != 2:
        raise ValueError("prediction and target must have equal shape (N,D).")
    if prediction.numel() == 0:
        raise ValueError("Cannot score an empty prediction tensor.")
    if not torch.isfinite(prediction).all() or not torch.isfinite(target).all():
        raise ValueError("Reconstruction metrics received non-finite tensors.")
    mse = F.mse_loss(prediction.float(), target.float())
    cosine = F.cosine_similarity(
        prediction.float(), target.float(), dim=-1, eps=1e-8
    )
    return {
        "rows": int(prediction.shape[0]),
        "mse": float(mse),
        "cosine_similarity_mean": float(cosine.mean()),
        "cosine_distance_mean": float((1.0 - cosine).mean()),
    }


def predictor_forward_batch(
    model: HistoryOnlyPredictor,
    history: Mapping[str, torch.Tensor],
    indices: torch.Tensor,
    *,
    device: torch.device,
) -> torch.Tensor:
    return model(
        history["features"][indices].to(device),
        history["valid_mask"][indices].to(device),
        history["unique_mask"][indices].to(device),
        history["role_index"].to(device),
        history["delta_days"][indices].to(device),
    )


def fit_predictor(
    *,
    history: Mapping[str, torch.Tensor],
    target_t0: torch.Tensor,
    train_indices: torch.Tensor,
    initial_state: Mapping[str, torch.Tensor],
    model_config: Mapping[str, Any],
    epochs: int,
    batch_size: int,
    learning_rate: float,
    weight_decay: float,
    grad_clip: float,
    cosine_weight: float,
    max_train_steps: int,
    seed: int,
    device: torch.device,
) -> tuple[HistoryOnlyPredictor, list[dict[str, Any]]]:
    if train_indices.ndim != 1 or train_indices.numel() == 0:
        raise ValueError("fit_predictor requires a non-empty 1-D train index.")
    model = HistoryOnlyPredictor(**model_config).to(device)
    model.load_state_dict(initial_state, strict=True)
    set_reproducible_seed(seed)
    optimizer = torch.optim.AdamW(
        model.parameters(), lr=learning_rate, weight_decay=weight_decay
    )
    records: list[dict[str, Any]] = []
    for epoch in range(1, int(epochs) + 1):
        model.train()
        local_batches = cache_runner.fixed_epoch_batches(
            int(train_indices.numel()),
            batch_size=int(batch_size),
            seed=int(seed),
            epoch=epoch,
            shuffle=True,
        )
        if max_train_steps:
            local_batches = local_batches[: int(max_train_steps)]
        sums = {"objective": 0.0, "mse": 0.0, "cosine_distance": 0.0}
        rows_seen = 0
        for step, local_indices in enumerate(local_batches, 1):
            indices = train_indices[local_indices]
            target = target_t0[indices].to(device)
            optimizer.zero_grad(set_to_none=True)
            prediction = predictor_forward_batch(
                model, history, indices, device=device
            )
            objective, mse, cosine_distance = predictor_loss_terms(
                prediction, target, cosine_weight=cosine_weight
            )
            if not torch.isfinite(objective):
                raise RuntimeError(
                    f"Predictor epoch={epoch} step={step} produced non-finite loss."
                )
            objective.backward()
            if grad_clip > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
            optimizer.step()
            batch_rows = int(indices.numel())
            sums["objective"] += float(objective.detach()) * batch_rows
            sums["mse"] += float(mse.detach()) * batch_rows
            sums["cosine_distance"] += float(cosine_distance.detach()) * batch_rows
            rows_seen += batch_rows
        if rows_seen == 0:
            raise RuntimeError("Predictor epoch executed zero optimizer steps.")
        records.append(
            {
                "epoch": epoch,
                "optimizer_steps": len(local_batches),
                "rows_seen": rows_seen,
                "objective": sums["objective"] / rows_seen,
                "mse": sums["mse"] / rows_seen,
                "cosine_distance": sums["cosine_distance"] / rows_seen,
            }
        )
    return model, records


def predict_history(
    model: HistoryOnlyPredictor,
    history: Mapping[str, torch.Tensor],
    *,
    batch_size: int,
    device: torch.device,
) -> torch.Tensor:
    rows = int(history["features"].shape[0])
    if rows == 0:
        raise ValueError("Cannot predict an empty history set.")
    outputs: list[torch.Tensor] = []
    model.eval()
    with torch.inference_mode():
        for indices in cache_runner.fixed_epoch_batches(
            rows, batch_size=batch_size, seed=0, epoch=0, shuffle=False
        ):
            outputs.append(
                predictor_forward_batch(
                    model, history, indices, device=device
                ).detach().cpu()
            )
    prediction = torch.cat(outputs, dim=0).contiguous()
    if not torch.isfinite(prediction).all():
        raise RuntimeError("Predictor emitted non-finite CLS values.")
    return prediction


def predictor_checkpoint(
    *,
    model: HistoryOnlyPredictor,
    initial_state_sha256: str,
    parameter_signature: Mapping[str, Any],
    model_config: Mapping[str, Any],
    training_history: Sequence[Mapping[str, Any]],
    train_events: Sequence[str],
    held_out_events: Sequence[str],
    held_out_metrics: Optional[Mapping[str, Any]],
    fold: str | int,
    args: argparse.Namespace,
    cache_audit: Mapping[str, Any],
) -> dict[str, Any]:
    train_set = set(str(value) for value in train_events)
    held_set = set(str(value) for value in held_out_events)
    overlap = sorted(train_set & held_set)
    if overlap:
        raise RuntimeError(f"Checkpoint event overlap is nonzero: {overlap[:5]}.")
    state = {
        name: value.detach().cpu()
        for name, value in model.state_dict().items()
    }
    return {
        "script_version": SCRIPT_VERSION,
        "fold": fold,
        "model": state,
        "model_state_sha256": cache_runner.state_dict_sha256(state),
        "initial_state_sha256": initial_state_sha256,
        "model_parameter_signature": dict(parameter_signature),
        "model_config": dict(model_config),
        "training_history": list(training_history),
        "train_events": len(train_set),
        "held_out_events": len(held_set),
        "train_event_sha256": hash_strings(sorted(train_set)),
        "held_out_event_sha256": hash_strings(sorted(held_set)),
        "event_overlap": 0,
        "held_out_metrics": (
            dict(held_out_metrics) if held_out_metrics is not None else None
        ),
        "cache_audit": dict(cache_audit),
        "args": serializable_args(args),
    }


def prediction_tensor_hashes(payload: Mapping[str, Any]) -> dict[str, str]:
    names = (
        "selected_cache_indices",
        "labels",
        "target_t0",
        "predicted_background",
        "shuffled_predicted_background",
        "fold_index",
        "shuffle_donor_row",
    )
    return {
        name: cache_runner.tensor_sha256(payload[name])
        for name in names
        if isinstance(payload.get(name), torch.Tensor)
    }


def build_prediction_payload(
    *,
    split: str,
    prediction_scope: str,
    cache_path: Path,
    cache_sha256: str,
    selected_cache_indices: torch.Tensor,
    data: Mapping[str, Any],
    target_t0: torch.Tensor,
    predicted_background: torch.Tensor,
    shuffled_predicted_background: torch.Tensor,
    fold_index: torch.Tensor,
    shuffle_donor_row: torch.Tensor,
    predictor_metrics: Mapping[str, Any],
    fold_audit: Sequence[Mapping[str, Any]],
    source_train_event_sha256: str,
) -> dict[str, Any]:
    rows = int(target_t0.shape[0])
    for name, tensor in (
        ("predicted_background", predicted_background),
        ("shuffled_predicted_background", shuffled_predicted_background),
    ):
        if tensor.shape != target_t0.shape:
            raise ValueError(f"{name} shape does not match target_t0.")
        if not torch.isfinite(tensor).all():
            raise ValueError(f"{name} contains non-finite values.")
    if fold_index.shape != (rows,) or shuffle_donor_row.shape != (rows,):
        raise ValueError("fold_index and shuffle_donor_row must have shape (N,).")
    event_ids = [str(value) for value in data["event_ids"]]
    donor_events = [event_ids[index] for index in shuffle_donor_row.tolist()]
    for target_event, donor_event in zip(event_ids, donor_events):
        if target_event == donor_event:
            raise RuntimeError("Prediction artifact has a same-event history donor.")
    payload: dict[str, Any] = {
        "format_version": PREDICTION_FORMAT_VERSION,
        "script_version": SCRIPT_VERSION,
        "split": split,
        "prediction_scope": prediction_scope,
        "cache_path": str(cache_path),
        "cache_sha256": cache_sha256,
        "selected_cache_indices": selected_cache_indices.long().cpu(),
        "ids": [str(value) for value in data["ids"]],
        "plume_ids": [str(value) for value in data["plume_ids"]],
        "event_ids": event_ids,
        "labels": data["labels"].long().cpu(),
        "target_t0": target_t0.float().cpu().contiguous(),
        "predicted_background": predicted_background.float().cpu().contiguous(),
        "shuffled_predicted_background": (
            shuffled_predicted_background.float().cpu().contiguous()
        ),
        "fold_index": fold_index.long().cpu(),
        "shuffle_donor_row": shuffle_donor_row.long().cpu(),
        "shuffle_donor_event_ids": donor_events,
        "predictor_metrics": dict(predictor_metrics),
        "fold_audit": [dict(value) for value in fold_audit],
        "event_overlap": 0,
        "source_train_event_sha256": source_train_event_sha256,
    }
    payload["tensor_sha256"] = prediction_tensor_hashes(payload)
    return payload


def write_prediction_artifact(path: Path, payload: Mapping[str, Any]) -> dict[str, Any]:
    cache_runner.atomic_torch_save(path, dict(payload))
    audit = {
        "path": str(path),
        "file_sha256": cache_runner.sha256_file(path),
        "tensor_sha256": dict(payload["tensor_sha256"]),
        "rows": int(payload["target_t0"].shape[0]),
        "prediction_scope": payload["prediction_scope"],
        "predictor_metrics": dict(payload["predictor_metrics"]),
    }
    cache_runner.atomic_json_write(path.with_suffix(path.suffix + ".json"), audit)
    return audit


def run_pretrain(args: argparse.Namespace) -> None:
    train_path = Path(args.train_cache).expanduser().resolve()
    val_path = Path(args.val_cache).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    if not train_path.is_file() or not val_path.is_file():
        raise FileNotFoundError("Both --train-cache and --val-cache must exist.")
    cache_runner.assert_not_sealed_path(output_dir, purpose="innovation pretrain output")
    if (output_dir / "summary.json").exists() and not args.overwrite:
        raise FileExistsError(
            f"{output_dir}/summary.json exists; pass --overwrite to replace artifacts."
        )
    output_dir.mkdir(parents=True, exist_ok=True)
    cache_runner.atomic_json_write(
        output_dir / "run_status.json",
        {
            "status": "running",
            "started_utc": pd.Timestamp.now(tz="UTC").isoformat(),
            "script_version": SCRIPT_VERSION,
            "sealed_test_read": False,
        },
    )
    try:
        train_cache, val_cache, cache_audit = cache_runner.load_cache_pair(
            train_path, val_path
        )
        train_indices = cache_runner.select_usable_rows(train_cache)
        val_indices = cache_runner.select_usable_rows(val_cache)
        train_data = cache_runner.take_rows(train_cache, train_indices)
        val_data = cache_runner.take_rows(val_cache, val_indices)
        t0_index = int(train_cache["t0_index"])
        role_index = train_cache["role_index"].long()
        train_history = extract_history_only_inputs(
            train_data, role_index=role_index, t0_index=t0_index
        )
        val_history = extract_history_only_inputs(
            val_data, role_index=role_index, t0_index=t0_index
        )
        target_train = train_history.pop("target_t0")
        target_val = val_history.pop("target_t0")
        device = resolve_device(args.device)
        args.resolved_device = device
        periods = parse_float_tuple(args.delta_periods)
        model_config = {
            "feature_dim": int(target_train.shape[1]),
            "num_roles": int(train_data["features"].shape[1]),
            "t0_index": t0_index,
            "model_dim": int(args.model_dim),
            "num_heads": int(args.num_heads),
            "depth": PREDICTOR_DEPTH,
            "mlp_ratio": float(args.mlp_ratio),
            "dropout": float(args.dropout),
            "periods_days": periods,
        }
        set_reproducible_seed(args.seed)
        prototype = HistoryOnlyPredictor(**model_config)
        initial_state = {
            name: value.detach().cpu().clone()
            for name, value in prototype.state_dict().items()
        }
        parameter_signature = cache_runner.model_parameter_signature(prototype)
        initial_state_sha = cache_runner.state_dict_sha256(initial_state)
        del prototype

        assignments, fold_audit = deterministic_event_folds(
            train_data["event_ids"], num_folds=args.folds, seed=args.seed
        )
        # Shuffled OOF controls require at least two unseen events within every
        # held-out fold.  Fail instead of borrowing a donor seen by the model.
        for audit in fold_audit:
            if int(audit["held_out_events"]) < 2:
                raise ValueError(
                    "Each held-out fold needs >=2 canonical events for a "
                    "leakage-safe history-shuffle control."
                )
        if len(set(val_data["event_ids"])) < 2:
            raise ValueError(
                "Validation needs >=2 canonical events for history shuffling."
            )

        train_rows = int(target_train.shape[0])
        oof_prediction = torch.empty_like(target_train)
        oof_shuffled_prediction = torch.empty_like(target_train)
        oof_donor_row = torch.full((train_rows,), -1, dtype=torch.long)
        seen = torch.zeros(train_rows, dtype=torch.int64)
        fold_results: list[dict[str, Any]] = []
        all_train_events = sorted(set(str(v) for v in train_data["event_ids"]))
        started = time.monotonic()

        for fold_index in range(int(args.folds)):
            held_indices = torch.nonzero(
                assignments == fold_index, as_tuple=False
            ).flatten()
            fit_indices = torch.nonzero(
                assignments != fold_index, as_tuple=False
            ).flatten()
            held_events = sorted(
                {str(train_data["event_ids"][index]) for index in held_indices.tolist()}
            )
            fit_events = sorted(
                {str(train_data["event_ids"][index]) for index in fit_indices.tolist()}
            )
            if set(held_events) & set(fit_events):
                raise RuntimeError(f"Fold {fold_index} canonical event overlap is nonzero.")
            model, training_history = fit_predictor(
                history=train_history,
                target_t0=target_train,
                train_indices=fit_indices,
                initial_state=initial_state,
                model_config=model_config,
                epochs=args.epochs,
                batch_size=args.batch_size,
                learning_rate=args.learning_rate,
                weight_decay=args.weight_decay,
                grad_clip=args.grad_clip,
                cosine_weight=args.cosine_weight,
                max_train_steps=args.max_train_steps,
                seed=args.seed + 10_007 * fold_index,
                device=device,
            )
            held_history = subset_history(train_history, held_indices)
            held_prediction = predict_history(
                model,
                held_history,
                batch_size=args.eval_batch_size,
                device=device,
            )
            held_metrics = reconstruction_metrics(
                held_prediction, target_train[held_indices]
            )
            held_event_rows = [
                str(train_data["event_ids"][index])
                for index in held_indices.tolist()
            ]
            local_donors = build_history_shuffle_donors(
                held_event_rows,
                seed=args.seed + 1_000_003 + fold_index,
            )
            shuffled_held_history = apply_history_only_donors(
                held_history, local_donors
            )
            held_shuffled_prediction = predict_history(
                model,
                shuffled_held_history,
                batch_size=args.eval_batch_size,
                device=device,
            )
            global_donors = held_indices[local_donors]
            for target_row, donor_row in zip(
                held_indices.tolist(), global_donors.tolist()
            ):
                if (
                    str(train_data["event_ids"][target_row])
                    == str(train_data["event_ids"][donor_row])
                ):
                    raise RuntimeError("OOF shuffle crossed no canonical-event boundary.")
            oof_prediction[held_indices] = held_prediction
            oof_shuffled_prediction[held_indices] = held_shuffled_prediction
            oof_donor_row[held_indices] = global_donors
            seen[held_indices] += 1

            checkpoint_path = output_dir / f"predictor_fold_{fold_index}.pt"
            checkpoint = predictor_checkpoint(
                model=model,
                initial_state_sha256=initial_state_sha,
                parameter_signature=parameter_signature,
                model_config=model_config,
                training_history=training_history,
                train_events=fit_events,
                held_out_events=held_events,
                held_out_metrics=held_metrics,
                fold=fold_index,
                args=args,
                cache_audit=cache_audit,
            )
            cache_runner.atomic_torch_save(checkpoint_path, checkpoint)
            fold_result = {
                **fold_audit[fold_index],
                "held_out_metrics": held_metrics,
                "training_history": training_history,
                "checkpoint": str(checkpoint_path),
                "checkpoint_sha256": cache_runner.sha256_file(checkpoint_path),
                "model_state_sha256": checkpoint["model_state_sha256"],
                "shuffle_scope": "within-held-out-fold-cross-canonical-event",
                "elapsed_seconds": float(time.monotonic() - started),
            }
            fold_results.append(fold_result)
            cache_runner.atomic_json_write(
                output_dir / "fold_results.json", fold_results
            )
            print(
                f"[innovation] fold={fold_index + 1}/{args.folds} "
                f"held_rows={len(held_indices)} MSE={held_metrics['mse']:.6f} "
                f"cos={held_metrics['cosine_similarity_mean']:.6f}",
                flush=True,
            )
            del model
            if device.type == "cuda":
                torch.cuda.empty_cache()

        if not torch.equal(seen, torch.ones_like(seen)):
            bad = torch.nonzero(seen != 1, as_tuple=False).flatten().tolist()
            raise RuntimeError(
                f"OOF coverage must be exactly once per row; bad rows={bad[:20]}."
            )
        if torch.any(oof_donor_row < 0):
            raise RuntimeError("OOF history donor assignment is incomplete.")
        oof_metrics = reconstruction_metrics(oof_prediction, target_train)
        oof_shuffle_metrics = reconstruction_metrics(
            oof_shuffled_prediction, target_train
        )

        all_indices = torch.arange(train_rows)
        final_model, final_training_history = fit_predictor(
            history=train_history,
            target_t0=target_train,
            train_indices=all_indices,
            initial_state=initial_state,
            model_config=model_config,
            epochs=args.epochs,
            batch_size=args.batch_size,
            learning_rate=args.learning_rate,
            weight_decay=args.weight_decay,
            grad_clip=args.grad_clip,
            cosine_weight=args.cosine_weight,
            max_train_steps=args.max_train_steps,
            seed=args.seed + 9_000_019,
            device=device,
        )
        validation_prediction = predict_history(
            final_model,
            val_history,
            batch_size=args.eval_batch_size,
            device=device,
        )
        val_donors = build_history_shuffle_donors(
            val_data["event_ids"], seed=args.seed + 2_000_003
        )
        shuffled_val_history = apply_history_only_donors(val_history, val_donors)
        validation_shuffled_prediction = predict_history(
            final_model,
            shuffled_val_history,
            batch_size=args.eval_batch_size,
            device=device,
        )
        validation_metrics = reconstruction_metrics(
            validation_prediction, target_val
        )
        validation_shuffle_metrics = reconstruction_metrics(
            validation_shuffled_prediction, target_val
        )
        final_checkpoint_path = output_dir / "predictor_final_all_train.pt"
        final_checkpoint = predictor_checkpoint(
            model=final_model,
            initial_state_sha256=initial_state_sha,
            parameter_signature=parameter_signature,
            model_config=model_config,
            training_history=final_training_history,
            train_events=all_train_events,
            held_out_events=sorted(set(str(v) for v in val_data["event_ids"])),
            held_out_metrics=validation_metrics,
            fold="final_all_train",
            args=args,
            cache_audit=cache_audit,
        )
        cache_runner.atomic_torch_save(final_checkpoint_path, final_checkpoint)

        train_event_sha = hash_strings(all_train_events)
        train_payload = build_prediction_payload(
            split="train",
            prediction_scope="event_cross_fitted_oof",
            cache_path=train_path,
            cache_sha256=cache_audit["train_cache_sha256"],
            selected_cache_indices=train_indices,
            data=train_data,
            target_t0=target_train,
            predicted_background=oof_prediction,
            shuffled_predicted_background=oof_shuffled_prediction,
            fold_index=assignments,
            shuffle_donor_row=oof_donor_row,
            predictor_metrics={
                "regular": oof_metrics,
                "history_shuffled": oof_shuffle_metrics,
            },
            fold_audit=fold_results,
            source_train_event_sha256=train_event_sha,
        )
        val_payload = build_prediction_payload(
            split="val",
            prediction_scope="all_train_final_predictor",
            cache_path=val_path,
            cache_sha256=cache_audit["validation_cache_sha256"],
            selected_cache_indices=val_indices,
            data=val_data,
            target_t0=target_val,
            predicted_background=validation_prediction,
            shuffled_predicted_background=validation_shuffled_prediction,
            fold_index=torch.full((len(val_data["ids"]),), -1, dtype=torch.long),
            shuffle_donor_row=val_donors,
            predictor_metrics={
                "regular": validation_metrics,
                "history_shuffled": validation_shuffle_metrics,
            },
            fold_audit=[],
            source_train_event_sha256=train_event_sha,
        )
        train_artifact = write_prediction_artifact(
            output_dir / "oof_train_predictions.pt", train_payload
        )
        val_artifact = write_prediction_artifact(
            output_dir / "final_validation_predictions.pt", val_payload
        )
        summary = {
            "script_version": SCRIPT_VERSION,
            "sealed_test_read": False,
            "cross_fitting": {
                "folds": int(args.folds),
                "assignment_unit": "canonical_event",
                "deterministic_seed": int(args.seed),
                "oof_coverage_exactly_once": True,
                "fold_event_overlap": 0,
                "fold_results": fold_results,
            },
            "history_only_contract": {
                "predictor_forward_accepts_t0": False,
                "input": [
                    "history_cls",
                    "history_role",
                    "real_delta_days",
                    "history_valid_mask",
                    "history_unique_mask",
                ],
                "target": "frozen_t0_cls",
                "usable_history_delta_constraint": "strictly_before_t0",
                "null_history_token_has_no_t0_or_label_information": True,
            },
            "oof_metrics": {
                "regular": oof_metrics,
                "history_shuffled": oof_shuffle_metrics,
            },
            "validation_metrics": {
                "regular": validation_metrics,
                "history_shuffled": validation_shuffle_metrics,
            },
            "final_predictor": {
                "checkpoint": str(final_checkpoint_path),
                "checkpoint_sha256": cache_runner.sha256_file(
                    final_checkpoint_path
                ),
                "model_state_sha256": final_checkpoint["model_state_sha256"],
                "training_history": final_training_history,
            },
            "prediction_artifacts": {
                "train": train_artifact,
                "validation": val_artifact,
            },
            "parameter_signature": parameter_signature,
            "initial_state_sha256": initial_state_sha,
            "model_config": {
                **model_config,
                "periods_days": list(periods),
            },
            "cache_audit": cache_audit,
            "train_rows_usable": train_rows,
            "validation_rows_usable": int(target_val.shape[0]),
            "args": serializable_args(args),
        }
        cache_runner.atomic_json_write(output_dir / "summary.json", summary)
        cache_runner.atomic_json_write(
            output_dir / "run_status.json",
            {
                "status": "complete",
                "completed_utc": pd.Timestamp.now(tz="UTC").isoformat(),
                "sealed_test_read": False,
                "oof_mse": oof_metrics["mse"],
                "validation_mse": validation_metrics["mse"],
            },
        )
        print(
            f"[innovation] complete OOF MSE={oof_metrics['mse']:.6f} "
            f"cos={oof_metrics['cosine_similarity_mean']:.6f}; "
            f"val MSE={validation_metrics['mse']:.6f} "
            f"cos={validation_metrics['cosine_similarity_mean']:.6f}",
            flush=True,
        )
    except Exception as error:
        cache_runner.atomic_json_write(
            output_dir / "run_status.json",
            {
                "status": "failed",
                "failed_utc": pd.Timestamp.now(tz="UTC").isoformat(),
                "error_type": type(error).__name__,
                "error": str(error),
                "sealed_test_read": False,
            },
        )
        raise


def compute_innovation(
    target_t0: torch.Tensor,
    predicted_background: torch.Tensor,
) -> torch.Tensor:
    if target_t0.shape != predicted_background.shape:
        raise ValueError("t0 and predicted background shapes must match.")
    return target_t0 - predicted_background.detach()


def build_downstream_slots(
    *,
    arm: str,
    target_t0: torch.Tensor,
    predicted_background: torch.Tensor,
    shuffled_predicted_background: torch.Tensor,
) -> torch.Tensor:
    if arm not in DOWNSTREAM_ARM_NAMES:
        raise ValueError(f"Unknown downstream arm {arm!r}.")
    if (
        target_t0.shape != predicted_background.shape
        or target_t0.shape != shuffled_predicted_background.shape
        or target_t0.ndim != 2
    ):
        raise ValueError("All downstream latent tensors must share shape (N,D).")
    background = predicted_background.detach()
    shuffled_background = shuffled_predicted_background.detach()
    zeros = torch.zeros_like(target_t0)
    innovation = compute_innovation(target_t0, background)
    shuffled_innovation = compute_innovation(
        target_t0, shuffled_background
    )
    if arm == "t0_only":
        pair = (target_t0, zeros)
    elif arm == "predicted_background_only":
        pair = (background, zeros)
    elif arm == "innovation_only":
        pair = (innovation, zeros)
    elif arm == "t0_plus_innovation":
        pair = (target_t0, innovation)
    else:
        pair = (shuffled_innovation, zeros)
    return torch.stack(pair, dim=1).contiguous()


class MatchedTwoSlotClassifier(nn.Module):
    """One static two-slot classifier architecture used by every probe arm."""

    def __init__(
        self,
        feature_dim: int,
        *,
        model_dim: int = 128,
        dropout: float = 0.1,
    ):
        super().__init__()
        if feature_dim <= 0 or model_dim <= 0:
            raise ValueError("feature_dim and model_dim must be positive.")
        self.feature_dim = int(feature_dim)
        self.input_norm = nn.LayerNorm(feature_dim)
        self.shared_projection = nn.Linear(feature_dim, model_dim)
        self.slot_embedding = nn.Parameter(torch.empty(1, 2, model_dim))
        nn.init.normal_(self.slot_embedding, std=0.02)
        self.mlp = nn.Sequential(
            nn.LayerNorm(2 * model_dim),
            nn.Linear(2 * model_dim, model_dim),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(model_dim, 1),
        )

    def forward(self, slots: torch.Tensor) -> torch.Tensor:
        if slots.ndim != 3 or slots.shape[1] != 2:
            raise ValueError("Matched classifier input must have shape (B,2,D).")
        if slots.shape[2] != self.feature_dim:
            raise ValueError(
                f"Expected slot feature_dim={self.feature_dim}, got {slots.shape[2]}."
            )
        encoded = self.shared_projection(self.input_norm(slots))
        encoded = encoded + self.slot_embedding
        return self.mlp(encoded.flatten(1)).squeeze(-1)


def validate_prediction_payload(
    *,
    path: Path,
    payload: Mapping[str, Any],
    expected_split: str,
    expected_scope: str,
    expected_cache_sha256: str,
    expected_selected_indices: torch.Tensor,
    data: Mapping[str, Any],
    expected_file_sha256: str,
    expected_t0_index: int,
) -> None:
    if cache_runner.sha256_file(path) != expected_file_sha256:
        raise ValueError(f"{path} file SHA differs from pretraining summary.")
    if payload.get("format_version") != PREDICTION_FORMAT_VERSION:
        raise ValueError(f"{path} has an unsupported prediction format.")
    if payload.get("script_version") != SCRIPT_VERSION:
        raise ValueError(f"{path} was not produced by this script version.")
    if payload.get("split") != expected_split:
        raise ValueError(f"{path} split does not equal {expected_split!r}.")
    if payload.get("prediction_scope") != expected_scope:
        raise ValueError(f"{path} has unexpected prediction scope.")
    if payload.get("cache_sha256") != expected_cache_sha256:
        raise ValueError(f"{path} cache SHA does not match the current cache.")
    if not torch.equal(
        payload["selected_cache_indices"].long(),
        expected_selected_indices.long(),
    ):
        raise ValueError(f"{path} selected cache rows do not align.")
    for name in ("ids", "plume_ids", "event_ids"):
        expected = [str(value) for value in data[name]]
        observed = [str(value) for value in payload[name]]
        if observed != expected:
            raise ValueError(f"{path} {name} do not exactly align with the cache.")
    if not torch.equal(payload["labels"].long(), data["labels"].long()):
        raise ValueError(f"{path} labels do not align with the cache.")
    if "target_t0" not in payload:
        raise ValueError(f"{path} lacks target_t0.")
    rows, feature_dim = payload["target_t0"].shape
    if not 0 <= int(expected_t0_index) < int(data["features"].shape[1]):
        raise ValueError("Expected t0 index is out of range.")
    if not torch.equal(
        payload["target_t0"].float(),
        data["features"][:, int(expected_t0_index)].float(),
    ):
        raise ValueError(
            f"{path} target_t0 does not exactly match the cache's declared t0 role."
        )
    if rows != len(data["ids"]) or feature_dim != int(data["features"].shape[-1]):
        raise ValueError(f"{path} target_t0 shape does not align.")
    for name in (
        "target_t0",
        "predicted_background",
        "shuffled_predicted_background",
    ):
        tensor = payload[name]
        if tensor.shape != (rows, feature_dim) or not torch.isfinite(tensor).all():
            raise ValueError(f"{path} {name} has an invalid shape or values.")
    observed_hashes = prediction_tensor_hashes(payload)
    if observed_hashes != payload.get("tensor_sha256"):
        raise ValueError(f"{path} tensor SHA metadata is invalid.")
    donors = payload["shuffle_donor_row"].long()
    if donors.shape != (rows,) or (
        donors.numel()
        and (int(donors.min()) < 0 or int(donors.max()) >= rows)
    ):
        raise ValueError(f"{path} has invalid history donor indices.")
    events = [str(value) for value in payload["event_ids"]]
    for row, donor in enumerate(donors.tolist()):
        if events[row] == events[donor]:
            raise ValueError(f"{path} has a same-event shuffled history donor.")
    if int(payload.get("event_overlap", -1)) != 0:
        raise ValueError(f"{path} records nonzero event overlap.")
    fold_index = payload["fold_index"].long()
    if fold_index.shape != (rows,):
        raise ValueError(f"{path} fold_index must have shape {(rows,)}.")
    if expected_scope == "event_cross_fitted_oof":
        if torch.any(fold_index < 0) or len(set(fold_index.tolist())) < 2:
            raise ValueError(f"{path} has invalid OOF fold assignments.")
        event_folds: dict[str, set[int]] = {}
        for event_id, fold in zip(events, fold_index.tolist()):
            event_folds.setdefault(event_id, set()).add(int(fold))
        split_events = {
            event_id: folds
            for event_id, folds in event_folds.items()
            if len(folds) != 1
        }
        if split_events:
            raise ValueError(
                f"{path} splits canonical events across OOF folds: "
                f"{list(split_events)[:10]}."
            )
        audits = payload.get("fold_audit")
        if not isinstance(audits, list) or not audits:
            raise ValueError(f"{path} lacks its fold exclusion audit.")
        if any(int(audit.get("event_overlap", -1)) != 0 for audit in audits):
            raise ValueError(f"{path} records a nonzero fold event overlap.")
    elif not torch.equal(fold_index, torch.full_like(fold_index, -1)):
        raise ValueError(f"{path} validation fold_index must be all -1.")


def load_aligned_prediction_data(
    *,
    pretrain_dir: Path,
    train_path: Path,
    val_path: Path,
) -> tuple[
    dict[str, Any],
    dict[str, Any],
    dict[str, Any],
    dict[str, Any],
    dict[str, Any],
]:
    cache_runner.assert_not_sealed_path(pretrain_dir, purpose="pretraining artifact")
    summary_path = pretrain_dir / "summary.json"
    if not summary_path.is_file():
        raise FileNotFoundError(f"Missing pretraining summary: {summary_path}.")
    summary = json.loads(summary_path.read_text(encoding="utf-8"))
    if summary.get("script_version") != SCRIPT_VERSION:
        raise ValueError("Pretraining summary script version mismatch.")
    if summary.get("sealed_test_read") is not False:
        raise ValueError("Pretraining summary does not prove sealed_test_read=false.")
    if (
        summary.get("cross_fitting", {}).get("fold_event_overlap") != 0
        or not summary.get("cross_fitting", {}).get("oof_coverage_exactly_once")
    ):
        raise ValueError("Pretraining summary has an invalid cross-fitting audit.")
    summary_fold_results = summary.get("cross_fitting", {}).get("fold_results")
    if not isinstance(summary_fold_results, list) or not summary_fold_results:
        raise ValueError("Pretraining summary lacks per-fold exclusion audits.")
    if any(
        int(result.get("event_overlap", -1)) != 0
        for result in summary_fold_results
    ):
        raise ValueError("Pretraining summary records nonzero fold event overlap.")
    train_cache, val_cache, cache_audit = cache_runner.load_cache_pair(
        train_path, val_path
    )
    train_indices = cache_runner.select_usable_rows(train_cache)
    val_indices = cache_runner.select_usable_rows(val_cache)
    train_data = cache_runner.take_rows(train_cache, train_indices)
    val_data = cache_runner.take_rows(val_cache, val_indices)
    train_prediction_path = pretrain_dir / "oof_train_predictions.pt"
    val_prediction_path = pretrain_dir / "final_validation_predictions.pt"
    train_prediction = cache_runner.torch_load_trusted(train_prediction_path)
    val_prediction = cache_runner.torch_load_trusted(val_prediction_path)
    train_artifact = summary["prediction_artifacts"]["train"]
    val_artifact = summary["prediction_artifacts"]["validation"]
    t0_index = int(train_cache["t0_index"])
    validate_prediction_payload(
        path=train_prediction_path,
        payload=train_prediction,
        expected_split="train",
        expected_scope="event_cross_fitted_oof",
        expected_cache_sha256=cache_audit["train_cache_sha256"],
        expected_selected_indices=train_indices,
        data=train_data,
        expected_file_sha256=train_artifact["file_sha256"],
        expected_t0_index=t0_index,
    )
    validate_prediction_payload(
        path=val_prediction_path,
        payload=val_prediction,
        expected_split="val",
        expected_scope="all_train_final_predictor",
        expected_cache_sha256=cache_audit["validation_cache_sha256"],
        expected_selected_indices=val_indices,
        data=val_data,
        expected_file_sha256=val_artifact["file_sha256"],
        expected_t0_index=t0_index,
    )
    if (
        train_prediction["source_train_event_sha256"]
        != val_prediction["source_train_event_sha256"]
    ):
        raise ValueError("Train and validation predictions use different train events.")
    expected_train_event_sha = hash_strings(
        sorted(set(str(value) for value in train_data["event_ids"]))
    )
    if (
        train_prediction["source_train_event_sha256"]
        != expected_train_event_sha
    ):
        raise ValueError("Prediction artifacts do not match the current train events.")
    return train_data, val_data, train_prediction, val_prediction, cache_audit


def binary_classification_metrics(
    labels: torch.Tensor,
    probability: np.ndarray,
    *,
    loss: float,
) -> dict[str, Any]:
    target = labels.long().cpu().numpy()
    if set(target.tolist()) != {0, 1}:
        raise ValueError("Binary metrics require both classes.")
    prediction = (probability >= 0.5).astype(np.int64)
    tn = int(np.sum((target == 0) & (prediction == 0)))
    fp = int(np.sum((target == 0) & (prediction == 1)))
    fn = int(np.sum((target == 1) & (prediction == 0)))
    tp = int(np.sum((target == 1) & (prediction == 1)))
    return {
        "loss": float(loss),
        "ap": float(average_precision_score(target, probability)),
        "auc": float(roc_auc_score(target, probability)),
        "macro_f1_at_0_5": float(
            f1_score(target, prediction, average="macro", zero_division=0)
        ),
        "balanced_accuracy_at_0_5": float(
            balanced_accuracy_score(target, prediction)
        ),
        "pred_positive_rate_at_0_5": float(prediction.mean()),
        "probability_min": float(probability.min()),
        "probability_max": float(probability.max()),
        "probability_mean": float(probability.mean()),
        "probability_std": float(probability.std()),
        "tn": tn,
        "fp": fp,
        "fn": fn,
        "tp": tp,
        "rows": int(target.shape[0]),
    }


def evaluate_classifier(
    model: MatchedTwoSlotClassifier,
    slots: torch.Tensor,
    labels: torch.Tensor,
    *,
    batch_size: int,
    device: torch.device,
    criterion: nn.Module,
) -> tuple[dict[str, Any], np.ndarray]:
    model.eval()
    probabilities: list[torch.Tensor] = []
    loss_sum = 0.0
    rows = int(labels.shape[0])
    with torch.inference_mode():
        for indices in cache_runner.fixed_epoch_batches(
            rows, batch_size=batch_size, seed=0, epoch=0, shuffle=False
        ):
            batch_labels = labels[indices].float().to(device)
            logits = model(slots[indices].to(device))
            loss = criterion(logits, batch_labels)
            loss_sum += float(loss) * len(indices)
            probabilities.append(torch.sigmoid(logits).cpu())
    probability = torch.cat(probabilities).numpy()
    return (
        binary_classification_metrics(
            labels, probability, loss=loss_sum / rows
        ),
        probability,
    )


def train_downstream_arm(
    arm: str,
    *,
    args: argparse.Namespace,
    train_slots: torch.Tensor,
    val_slots: torch.Tensor,
    train_data: Mapping[str, Any],
    val_data: Mapping[str, Any],
    initial_state: Mapping[str, torch.Tensor],
    parameter_signature: Mapping[str, Any],
    artifact_audit: Mapping[str, Any],
    output_dir: Path,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    model = MatchedTwoSlotClassifier(
        feature_dim=int(train_slots.shape[-1]),
        model_dim=args.model_dim,
        dropout=args.dropout,
    ).to(args.resolved_device)
    model.load_state_dict(initial_state, strict=True)
    if cache_runner.model_parameter_signature(model) != parameter_signature:
        raise RuntimeError(f"{arm} classifier parameter signature changed.")
    set_reproducible_seed(args.seed)
    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.learning_rate,
        weight_decay=args.weight_decay,
    )
    labels = train_data["labels"].float()
    positives = float(labels.sum())
    negatives = float(labels.numel() - positives)
    criterion = nn.BCEWithLogitsLoss(
        pos_weight=torch.tensor(
            negatives / max(positives, 1.0), device=args.resolved_device
        )
    )
    arm_dir = output_dir / arm
    arm_dir.mkdir(parents=True, exist_ok=True)
    history: list[dict[str, Any]] = []
    best: Optional[dict[str, Any]] = None
    started = time.monotonic()
    for epoch in range(1, int(args.epochs) + 1):
        model.train()
        batches = cache_runner.fixed_epoch_batches(
            int(labels.shape[0]),
            batch_size=args.batch_size,
            seed=args.seed,
            epoch=epoch,
            shuffle=True,
        )
        if args.max_train_steps:
            batches = batches[: int(args.max_train_steps)]
        loss_sum = 0.0
        rows_seen = 0
        for step, indices in enumerate(batches, 1):
            batch_labels = labels[indices].to(args.resolved_device)
            optimizer.zero_grad(set_to_none=True)
            logits = model(train_slots[indices].to(args.resolved_device))
            loss = criterion(logits, batch_labels)
            if not torch.isfinite(loss):
                raise RuntimeError(
                    f"{arm} epoch={epoch} step={step} produced non-finite loss."
                )
            loss.backward()
            if args.grad_clip > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)
            optimizer.step()
            loss_sum += float(loss.detach()) * len(indices)
            rows_seen += len(indices)
        validation, probability = evaluate_classifier(
            model,
            val_slots,
            val_data["labels"],
            batch_size=args.eval_batch_size,
            device=args.resolved_device,
            criterion=criterion,
        )
        record = {
            "arm": arm,
            "epoch": epoch,
            "optimizer_steps": len(batches),
            "train_rows_seen": rows_seen,
            "train_loss": loss_sum / max(rows_seen, 1),
            "validation": validation,
            "elapsed_seconds": float(time.monotonic() - started),
        }
        history.append(record)
        if best is None or validation["ap"] > best["validation"]["ap"]:
            best = copy.deepcopy(record)
            state = {
                name: value.detach().cpu()
                for name, value in model.state_dict().items()
            }
            checkpoint = {
                "script_version": SCRIPT_VERSION,
                "arm": arm,
                "epoch": epoch,
                "model": state,
                "model_state_sha256": cache_runner.state_dict_sha256(state),
                "initial_state_sha256": cache_runner.state_dict_sha256(
                    initial_state
                ),
                "model_parameter_signature": dict(parameter_signature),
                "artifact_audit": dict(artifact_audit),
                "validation": validation,
                "args": serializable_args(args),
            }
            cache_runner.atomic_torch_save(
                arm_dir / "checkpoint_best_ap.pt", checkpoint
            )
            predictions = pd.DataFrame(
                {
                    "id": val_data["ids"],
                    "plume_id": val_data["plume_ids"],
                    "event_id": val_data["event_ids"],
                    "label": val_data["labels"].long().tolist(),
                    "probability": probability,
                    "prediction_at_0_5": (
                        probability >= 0.5
                    ).astype(np.int64),
                    "arm": arm,
                    "epoch": epoch,
                }
            )
            cache_runner.atomic_csv_write(
                arm_dir / "validation_best_ap_predictions.csv", predictions
            )
        cache_runner.atomic_json_write(
            arm_dir / "metrics_history.json", history
        )
        print(
            f"[downstream] arm={arm} epoch={epoch}/{args.epochs} "
            f"loss={record['train_loss']:.6f} AP={validation['ap']:.6f} "
            f"AUC={validation['auc']:.6f} "
            f"macroF1={validation['macro_f1_at_0_5']:.6f} "
            f"BA={validation['balanced_accuracy_at_0_5']:.6f} "
            f"pred+={validation['pred_positive_rate_at_0_5']:.6f}",
            flush=True,
        )
    if best is None:
        raise RuntimeError(f"{arm} produced no epoch result.")
    return history, best


def run_downstream(args: argparse.Namespace) -> None:
    train_path = Path(args.train_cache).expanduser().resolve()
    val_path = Path(args.val_cache).expanduser().resolve()
    pretrain_dir = Path(args.pretrain_dir).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    if not train_path.is_file() or not val_path.is_file():
        raise FileNotFoundError("Both --train-cache and --val-cache must exist.")
    cache_runner.assert_not_sealed_path(output_dir, purpose="downstream output")
    if (output_dir / "summary.json").exists() and not args.overwrite:
        raise FileExistsError(
            f"{output_dir}/summary.json exists; pass --overwrite to replace artifacts."
        )
    output_dir.mkdir(parents=True, exist_ok=True)
    cache_runner.atomic_json_write(
        output_dir / "run_status.json",
        {
            "status": "running",
            "started_utc": pd.Timestamp.now(tz="UTC").isoformat(),
            "script_version": SCRIPT_VERSION,
            "sealed_test_read": False,
        },
    )
    try:
        (
            train_data,
            val_data,
            train_prediction,
            val_prediction,
            cache_audit,
        ) = load_aligned_prediction_data(
            pretrain_dir=pretrain_dir,
            train_path=train_path,
            val_path=val_path,
        )
        arms = cache_runner.parse_columns(args.arms)
        unknown = sorted(set(arms) - set(DOWNSTREAM_ARM_NAMES))
        if unknown:
            raise ValueError(
                f"Unknown arms={unknown}; expected {DOWNSTREAM_ARM_NAMES}."
            )
        if len(set(arms)) != len(arms):
            raise ValueError("Downstream arms must be unique.")
        train_slots = {
            arm: build_downstream_slots(
                arm=arm,
                target_t0=train_prediction["target_t0"].float(),
                predicted_background=train_prediction[
                    "predicted_background"
                ].float(),
                shuffled_predicted_background=train_prediction[
                    "shuffled_predicted_background"
                ].float(),
            )
            for arm in arms
        }
        val_slots = {
            arm: build_downstream_slots(
                arm=arm,
                target_t0=val_prediction["target_t0"].float(),
                predicted_background=val_prediction[
                    "predicted_background"
                ].float(),
                shuffled_predicted_background=val_prediction[
                    "shuffled_predicted_background"
                ].float(),
            )
            for arm in arms
        }
        shapes = {tuple(value.shape) for value in train_slots.values()}
        val_shapes = {tuple(value.shape) for value in val_slots.values()}
        if len(shapes) != 1 or len(val_shapes) != 1:
            raise RuntimeError("All downstream arms must use identical static shapes.")
        device = resolve_device(args.device)
        args.resolved_device = device
        set_reproducible_seed(args.seed)
        prototype = MatchedTwoSlotClassifier(
            feature_dim=int(next(iter(train_slots.values())).shape[-1]),
            model_dim=args.model_dim,
            dropout=args.dropout,
        )
        initial_state = {
            name: value.detach().cpu().clone()
            for name, value in prototype.state_dict().items()
        }
        parameter_signature = cache_runner.model_parameter_signature(prototype)
        initial_state_sha = cache_runner.state_dict_sha256(initial_state)
        del prototype
        artifact_audit = {
            "pretrain_dir": str(pretrain_dir),
            "pretrain_summary_sha256": cache_runner.sha256_file(
                pretrain_dir / "summary.json"
            ),
            "oof_train_predictions_sha256": cache_runner.sha256_file(
                pretrain_dir / "oof_train_predictions.pt"
            ),
            "final_validation_predictions_sha256": cache_runner.sha256_file(
                pretrain_dir / "final_validation_predictions.pt"
            ),
            "train_prediction_scope": train_prediction["prediction_scope"],
            "validation_prediction_scope": val_prediction["prediction_scope"],
            "train_validation_event_overlap": 0,
        }
        run_config = {
            "script_version": SCRIPT_VERSION,
            "arms": list(arms),
            "seed": int(args.seed),
            "epochs": int(args.epochs),
            "batch_size": int(args.batch_size),
            "eval_batch_size": int(args.eval_batch_size),
            "model_dim": int(args.model_dim),
            "dropout": float(args.dropout),
            "static_input_shape": list(next(iter(shapes))),
            "parameter_signature": parameter_signature,
            "initial_state_sha256": initial_state_sha,
            "matched_compute_contract": {
                "same_initial_state": True,
                "same_parameter_shapes": True,
                "same_static_two_slot_shape": True,
                "same_epoch_batches": True,
                "same_optimizer_and_steps": True,
                "same_dropout_rng_seed": True,
            },
            "representation_contract": {
                "t0_only": "[z0, zero]",
                "predicted_background_only": "[stopgrad(bhat), zero]",
                "innovation_only": "[z0-stopgrad(bhat), zero]",
                "t0_plus_innovation": "[z0, z0-stopgrad(bhat)]",
                "history_shuffle_innovation": (
                    "[z0-stopgrad(bhat_from_cross_event_shuffled_history), zero]"
                ),
                "t0_plus_innovation_interpretation": (
                    "redundant algebraic reparameterization control: bhat is "
                    "recoverable as z0-(z0-bhat), so this arm is not independent "
                    "evidence for innovation"
                ),
            },
            "artifact_audit": artifact_audit,
            "cache_audit": cache_audit,
        }
        cache_runner.atomic_json_write(
            output_dir / "run_config.json", run_config
        )
        all_history: dict[str, list[dict[str, Any]]] = {}
        best_by_arm: dict[str, dict[str, Any]] = {}
        for arm in arms:
            history, best = train_downstream_arm(
                arm,
                args=args,
                train_slots=train_slots[arm],
                val_slots=val_slots[arm],
                train_data=train_data,
                val_data=val_data,
                initial_state=initial_state,
                parameter_signature=parameter_signature,
                artifact_audit=artifact_audit,
                output_dir=output_dir,
            )
            all_history[arm] = history
            best_by_arm[arm] = best
            cache_runner.atomic_json_write(
                output_dir / "metrics_history.json", all_history
            )
            cache_runner.atomic_json_write(
                output_dir / "summary.json",
                {
                    "script_version": SCRIPT_VERSION,
                    "best_by_arm": best_by_arm,
                    "selection_metric": "validation_ap",
                    "sealed_test_read": False,
                    "initial_state_sha256": initial_state_sha,
                    "parameter_signature": parameter_signature,
                    "matched_compute_contract": run_config[
                        "matched_compute_contract"
                    ],
                    "representation_contract": run_config[
                        "representation_contract"
                    ],
                    "artifact_audit": artifact_audit,
                    "cache_audit": cache_audit,
                },
            )
        cache_runner.atomic_json_write(
            output_dir / "run_status.json",
            {
                "status": "complete",
                "completed_utc": pd.Timestamp.now(tz="UTC").isoformat(),
                "arms": list(arms),
                "sealed_test_read": False,
            },
        )
    except Exception as error:
        cache_runner.atomic_json_write(
            output_dir / "run_status.json",
            {
                "status": "failed",
                "failed_utc": pd.Timestamp.now(tz="UTC").isoformat(),
                "error_type": type(error).__name__,
                "error": str(error),
                "sealed_test_read": False,
            },
        )
        raise


