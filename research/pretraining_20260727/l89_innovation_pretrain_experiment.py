def set_reproducible_seed(seed: int) -> None:
    random.seed(int(seed))
    np.random.seed(int(seed))
    torch.manual_seed(int(seed))
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(int(seed))


def resolve_device(value: str) -> torch.device:
    device = torch.device(value)
    if device.type == "cuda" and device.index is None:
        device = torch.device("cuda:0")
    if device.type == "cuda":
        if not torch.cuda.is_available():
            raise RuntimeError(f"CUDA device {device} requested but CUDA is unavailable.")
        torch.cuda.set_device(device)
    return device


def parse_float_tuple(value: str) -> tuple[float, ...]:
    result = tuple(float(part.strip()) for part in value.split(",") if part.strip())
    if not result or any(not math.isfinite(item) or item <= 0 for item in result):
        raise ValueError(f"Expected positive finite comma-separated values, got {value!r}.")
    return result


def hash_strings(values: Sequence[str]) -> str:
    return cache_runner.sha256_bytes(
        cache_runner.canonical_json_bytes([str(value) for value in values])
    )


def serializable_args(args: argparse.Namespace) -> dict[str, Any]:
    return {
        key: value
        for key, value in vars(args).items()
        if key not in {"resolved_device"} and not callable(value)
    }


def history_role_indices(num_roles: int, t0_index: int) -> torch.Tensor:
    if not 0 <= int(t0_index) < int(num_roles):
        raise ValueError("t0_index is out of range.")
    return torch.tensor(
        [index for index in range(int(num_roles)) if index != int(t0_index)],
        dtype=torch.long,
    )


def extract_history_only_inputs(
    data: Mapping[str, Any],
    *,
    role_index: torch.Tensor,
    t0_index: int,
) -> dict[str, torch.Tensor]:
    """Separate history tensors from the target before calling the predictor."""

    features = data["features"].float()
    valid_mask = data["valid_mask"].bool()
    unique_mask = data["unique_mask"].bool()
    delta_days = data["delta_days"].float()
    if features.ndim != 3:
        raise ValueError("Cached features must have shape (N,T,D).")
    rows, timepoints, _ = features.shape
    expected = (rows, timepoints)
    for name, value in (
        ("valid_mask", valid_mask),
        ("unique_mask", unique_mask),
        ("delta_days", delta_days),
    ):
        if value.shape != expected:
            raise ValueError(f"{name} must have shape {expected}, got {value.shape}.")
    if role_index.shape != (timepoints,):
        raise ValueError(
            f"role_index must have shape {(timepoints,)}, got {role_index.shape}."
        )
    if not torch.isfinite(features).all():
        raise ValueError("Cached CLS features contain non-finite values.")
    history = history_role_indices(timepoints, t0_index)
    target_t0 = features[:, int(t0_index)].contiguous()
    history_valid = valid_mask[:, history].contiguous()
    history_unique = unique_mask[:, history].contiguous()
    history_delta = delta_days[:, history].contiguous()
    effective_history = history_valid & history_unique
    if torch.any(effective_history & ~torch.isfinite(history_delta)):
        raise ValueError("A usable history observation has a non-finite real delta.")
    if torch.any(effective_history & (history_delta >= 0)):
        raise ValueError(
            "Past-to-t0 prediction refuses usable history at or after t0."
        )
    return {
        "features": features[:, history].contiguous(),
        "valid_mask": history_valid,
        "unique_mask": history_unique,
        "delta_days": history_delta,
        "role_index": role_index[history].long().contiguous(),
        "target_t0": target_t0,
    }


class HistoryOnlyPredictor(nn.Module):
    """Predict t0 CLS from past observations without accepting t0 as input."""

    def __init__(
        self,
        feature_dim: int,
        num_roles: int,
        *,
        t0_index: int,
        model_dim: int = 128,
        num_heads: int = 4,
        depth: int = PREDICTOR_DEPTH,
        mlp_ratio: float = 2.0,
        dropout: float = 0.1,
        periods_days: Sequence[float] = (1, 3, 7, 30, 90, 365),
    ):
        super().__init__()
        if depth != PREDICTOR_DEPTH:
            raise ValueError(f"The predictor has exactly {PREDICTOR_DEPTH} layers.")
        if model_dim % num_heads:
            raise ValueError("model_dim must be divisible by num_heads.")
        if feature_dim <= 0 or num_roles < 2:
            raise ValueError("feature_dim must be positive and num_roles must be >=2.")
        if not 0 <= int(t0_index) < int(num_roles):
            raise ValueError("t0_index is out of range.")
        self.feature_dim = int(feature_dim)
        self.num_roles = int(num_roles)
        self.t0_index = int(t0_index)
        self.input_projection = nn.Linear(feature_dim, model_dim)
        self.role_embedding = nn.Embedding(num_roles, model_dim)
        self.delta_encoder = cache_runner.ContinuousDeltaEncoder(
            model_dim, periods_days
        )
        self.input_norm = nn.LayerNorm(model_dim)
        self.history_query = nn.Parameter(torch.empty(1, 1, model_dim))
        self.null_history_token = nn.Parameter(torch.empty(1, 1, model_dim))
        nn.init.normal_(self.history_query, std=0.02)
        nn.init.normal_(self.null_history_token, std=0.02)
        self.blocks = nn.ModuleList(
            [
                cache_runner.CurrentQueryBlock(
                    model_dim,
                    num_heads,
                    mlp_ratio=mlp_ratio,
                    dropout=dropout,
                )
                for _ in range(depth)
            ]
        )
        self.output_norm = nn.LayerNorm(model_dim)
        self.output_projection = nn.Linear(model_dim, feature_dim)

    def forward(
        self,
        history_features: torch.Tensor,
        history_valid_mask: torch.Tensor,
        history_unique_mask: torch.Tensor,
        history_role_index: torch.Tensor,
        history_delta_days: torch.Tensor,
    ) -> torch.Tensor:
        if history_features.ndim != 3:
            raise ValueError("history_features must have shape (B,H,D).")
        batch_size, history_length, feature_dim = history_features.shape
        if feature_dim != self.feature_dim:
            raise ValueError(
                f"Expected history feature_dim={self.feature_dim}, got {feature_dim}."
            )
        expected = (batch_size, history_length)
        if history_valid_mask.shape != expected:
            raise ValueError("history_valid_mask shape does not match history features.")
        if history_unique_mask.shape != expected:
            raise ValueError("history_unique_mask shape does not match history features.")
        if history_delta_days.shape != expected:
            raise ValueError("history_delta_days shape does not match history features.")
        if history_role_index.ndim == 1:
            history_role_index = history_role_index.view(1, -1).expand(
                batch_size, -1
            )
        if history_role_index.shape != expected:
            raise ValueError("history_role_index shape does not match history features.")
        if torch.any(history_role_index == self.t0_index):
            raise ValueError(
                "HistoryOnlyPredictor refuses a role_index containing the t0 role."
            )
        if torch.any(history_role_index < 0) or torch.any(
            history_role_index >= self.num_roles
        ):
            raise ValueError("history_role_index contains an out-of-range role.")
        if not torch.isfinite(history_features).all():
            raise ValueError("history_features contain non-finite values.")

        effective_valid = history_valid_mask.bool() & history_unique_mask.bool()
        if torch.any(effective_valid & ~torch.isfinite(history_delta_days)):
            raise ValueError("A usable history token has a non-finite delta.")
        if torch.any(effective_valid & (history_delta_days >= 0)):
            raise ValueError(
                "HistoryOnlyPredictor refuses usable observations at or after t0."
            )
        context = (
            self.input_projection(history_features)
            + self.role_embedding(history_role_index.long())
            + self.delta_encoder(history_delta_days)
        )
        context = self.input_norm(context)
        # The learned null token keeps attention well-defined for rows with no
        # usable history; it contains no t0 or label information.
        null_token = self.null_history_token.expand(batch_size, -1, -1)
        context = torch.cat((context, null_token), dim=1)
        context_valid = torch.cat(
            (
                effective_valid,
                torch.ones(
                    batch_size,
                    1,
                    dtype=torch.bool,
                    device=effective_valid.device,
                ),
            ),
            dim=1,
        )
        query = self.history_query.expand(batch_size, -1, -1)
        for block in self.blocks:
            query = block(query, context, context_valid)
        return self.output_projection(self.output_norm(query[:, 0]))


def deterministic_event_folds(
    event_ids: Sequence[str],
    *,
    num_folds: int,
    seed: int,
) -> tuple[torch.Tensor, list[dict[str, Any]]]:
    """Assign complete canonical events to deterministic shuffled K folds."""

    if int(num_folds) < 2:
        raise ValueError("Cross-fitting requires at least two folds.")
    events = [str(value) for value in event_ids]
    unique_events = sorted(set(events))
    if len(unique_events) < int(num_folds):
        raise ValueError(
            f"Need at least {num_folds} events for cross-fitting, got "
            f"{len(unique_events)}."
        )
    shuffled = list(unique_events)
    random.Random(int(seed)).shuffle(shuffled)
    event_to_fold = {
        event_id: position % int(num_folds)
        for position, event_id in enumerate(shuffled)
    }
    assignments = torch.tensor(
        [event_to_fold[event_id] for event_id in events], dtype=torch.long
    )
    audit: list[dict[str, Any]] = []
    all_events = set(unique_events)
    for fold_index in range(int(num_folds)):
        held_events = sorted(
            event_id
            for event_id, assigned_fold in event_to_fold.items()
            if assigned_fold == fold_index
        )
        train_events = sorted(all_events - set(held_events))
        overlap = sorted(set(train_events) & set(held_events))
        if overlap:
            raise RuntimeError(f"Fold {fold_index} event exclusion failed: {overlap[:5]}.")
        if not held_events or not train_events:
            raise ValueError(f"Fold {fold_index} has an empty train or held-out event set.")
        audit.append(
            {
                "fold": fold_index,
                "train_events": len(train_events),
                "held_out_events": len(held_events),
                "train_event_sha256": hash_strings(train_events),
                "held_out_event_sha256": hash_strings(held_events),
                "event_overlap": 0,
                "train_rows": int((assignments != fold_index).sum()),
                "held_out_rows": int((assignments == fold_index).sum()),
            }
        )
    return assignments, audit


def build_history_shuffle_donors(
    event_ids: Sequence[str],
    *,
    seed: int,
) -> torch.Tensor:
    donors = cache_runner.build_cross_event_donor_indices(event_ids, seed=seed)
    for target, donor in enumerate(donors.tolist()):
        if str(event_ids[target]) == str(event_ids[donor]):
            raise RuntimeError("History shuffle donor shares the target canonical event.")
    return donors


def apply_history_only_donors(
    history: Mapping[str, torch.Tensor],
    donor_indices: torch.Tensor,
) -> dict[str, torch.Tensor]:
    rows = int(history["features"].shape[0])
    if donor_indices.shape != (rows,):
        raise ValueError("donor_indices must have one entry per history row.")
    if donor_indices.numel() and (
        int(donor_indices.min()) < 0 or int(donor_indices.max()) >= rows
    ):
        raise ValueError("donor_indices contains an out-of-range row.")
    # role_index is a static schema, not an observation from a donor row.
    return {
        "features": history["features"][donor_indices].clone(),
        "valid_mask": history["valid_mask"][donor_indices].clone(),
        "unique_mask": history["unique_mask"][donor_indices].clone(),
        "delta_days": history["delta_days"][donor_indices].clone(),
        "role_index": history["role_index"].clone(),
    }


